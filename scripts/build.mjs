import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root = new URL('../',import.meta.url);
const provider=readFileSync(new URL('src/provider.mjs',root),'utf8').replace("import matrix from './matrix.json' with {type:'json'};", 'const matrix = '+readFileSync(new URL('src/matrix.json',root),'utf8')+';');
const main=readFileSync(new URL('src/main.mjs',root),'utf8').replace('#!/usr/bin/env node\n','').replace("import {dispatch, Refusal} from './provider.mjs';\n",'');
const bytes='#!/usr/bin/env node\n// Generated by scripts/build.mjs. No dependencies or lifecycle hooks.\n'+provider+'\n'+main;
const out=new URL('bin/lekalo-postgres.mjs',root);
if (process.argv.includes('--check')) { if (readFileSync(out,'utf8')!==bytes) throw new Error('bundle drift'); }
else writeFileSync(out,bytes,{mode:0o755});
